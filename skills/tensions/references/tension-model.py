# The Tension domain model, as written in the Linear project "Tensions" (project content).
# Reference only: the runtime API is Tensions.read/emit in scripts/app_tensions.py.

class Tension:  # Aggregate Root / domain API
    id: str
    actual: Any
    desired: Any
    context: dict

    # Management
    @classmethod
    def create(cls, definition): ...
    def redefine(self, definition): ...
    def resolve(self, resolution): ...
    def reopen(self, reason): ...
    def archive(self, reason): ...

    # Observation
    def record(self, observation, evidence=None): ...
    def correct(self, observation): ...
    def dispute(self, evidence, reason): ...

    # Reasoning
    def propose_hypothesis(self, hypothesis): ...
    def assess(self, assessment): ...
    def challenge(self, assessment): ...

    # Relationship
    def link(self, relationship): ...
    def unlink(self, relationship): ...
    def decompose(self, relationship): ...

    # Action
    def propose(self, proposal): ...
    def start(self, proposal): ...
    def complete(self, outcome): ...
    def fail(self, outcome): ...

    # Domain queries (projected from history)
    def state(self): ...
    def history(self): ...
    def observations(self): ...
    def relationships(self): ...


class Tensions:  # skills/tensions/scripts/app_tensions.py
    def read(self, query): ...
    def emit(self, event, value, tension_id=None): ...
